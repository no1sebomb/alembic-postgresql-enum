INDENTED_TEMPLATE = '''"""${message}"""

from alembic import op
import sqlalchemy as sa
${imports if imports else ""}

revision = ${repr(up_revision)}


def upgrade():
    ${enums if enums else ""}
    ${upgrades if upgrades else "pass"}


def downgrade():
    ${enums if enums else ""}
    ${downgrades if downgrades else "pass"}
'''


def test_enums_are_indented_to_match_template(connection: "Connection", tmp_path):
    """Check that enums can be defined inside upgrade and downgrade functions"""
    script_directory = tmp_path / "migrations"
    (script_directory / "versions").mkdir(parents=True)
    (script_directory / "script.py.mako").write_text(INDENTED_TEMPLATE)

    alembic_config = AlembicConfig()
    alembic_config.set_main_option("script_location", str(script_directory))
    revision_template_args: Dict[str, Any] = {"config": alembic_config}

    old_configuration = get_configuration()
    alembic_postgresql_enum.set_configuration(Config(module_level_enums=True))
    try:
        migration_context = create_migration_context(
            connection,
            get_schema_with_enum_variants(["active", "passive"]),
            migration_options_overrides={"template_args": revision_template_args},
        )

        template_args: Dict[str, Any] = {}
        autogenerate._render_migration_diffs(migration_context, template_args)
    finally:
        alembic_postgresql_enum.set_configuration(old_configuration)

    # first line is indented by the template itself, the rest are indented by the library
    assert revision_template_args["enums"] == definitions_block(
        f"{USER_STATUS_ENUM_NAME} = postgresql.ENUM('active', 'passive',"
        f" name='{USER_STATUS_ENUM_NAME}', create_type=False)"
    ).replace("\n", "\n    ")

    migration = Template(text=INDENTED_TEMPLATE).render(
        message="test",
        up_revision="abc123",
        **revision_template_args,
        **template_args,
    )
    compile(migration, "migration.py", "exec")
