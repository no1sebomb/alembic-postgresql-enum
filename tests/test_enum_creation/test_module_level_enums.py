POSTGRESQL_IMPORT = "from sqlalchemy.dialects import postgresql"


def definitions_block(*definitions: str) -> str:
    """Enum definitions as they are rendered into generated migration"""
    return "\n".join((ENUM_DEFINITIONS_HEADER, *definitions, ENUM_DEFINITIONS_FOOTER))


def expected_imports(*definitions: str, other_imports: Sequence[str] = ()) -> str:
    """Imports section of generated migration with enum definitions at the end of it"""
    imports = sorted((POSTGRESQL_IMPORT, *other_imports))
    return "\n".join((*imports, "", definitions_block(*definitions)))


